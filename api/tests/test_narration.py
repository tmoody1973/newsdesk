# --- the correction ladder -------------------------------------------------


def test_pauses_land_between_sentences():
    out = paced(LINE, "[pause]")
    assert out.count("[pause]") == 2


def test_no_pause_is_added_after_the_final_sentence():
    """A trailing pause is trailing silence, and the trim removes it.

    Adding one would cost a take and change nothing measurable.
    """
    assert not paced(LINE, "[pause]").rstrip().endswith("[pause]")


def test_a_single_sentence_is_left_alone():
    one = "Nobody announced it."
    assert paced(one, "[pause]") == one


def test_pacing_does_not_change_the_words():
    spoken = paced(LINE, "[pause]").replace("[pause]", "")
    assert spoken.split() == LINE.split()


@pytest.mark.parametrize(
    ("deficit", "tag"), [(0.15, "[pause]"), (0.5, "[pause]"), (2.4, "[long pause]")]
)
def test_the_notch_is_sized_by_the_deficit(deficit, tag):
    assert pause_tag(deficit, boundaries=1) == tag


def test_every_notch_has_a_measured_gain_behind_it():
    """`[short pause]` was dropped, and this is what stops it coming back.

    It was never measured to buy anything. The spike quantified `[pause]` at
    +0.36s per boundary and `[long pause]` at +1.25s; `[short pause]` sat below
    both by assumption alone, and on the live CS-1 run it twice failed to move a
    0.26s deficit on block 6 — two corrections, $0.07, no change. A notch that
    costs a take and buys nothing measurable is worse than no notch, because it
    consumes one of the two attempts an editor is waiting on.
    """
    assert PAUSE_TAGS == ("[pause]", "[long pause]")


def test_the_notch_is_sized_per_boundary_not_per_take():
    """The same deficit needs a smaller notch when there are more places to put it.

    Measured on eleven_v3: `[pause]` buys about 0.36s at each internal sentence
    boundary and `[long pause]` about 1.25s. So a 0.9s deficit is one `[pause]`
    per boundary across three of them, and a single `[long pause]` across one.
    Sizing against the whole deficit under-fires on a two-sentence block, which
    is exactly how block 6 of the live CS-1 run burned two corrections and
    stayed short.
    """
    assert pause_tag(0.9, boundaries=3) == "[pause]"
    assert pause_tag(0.9, boundaries=1) == "[long pause]"


def test_the_notch_escalates_on_a_second_attempt():
    """A first correction that undershot should not be repeated identically."""
    first = pause_tag(0.15, boundaries=1)
    second = pause_tag(0.15, boundaries=1, bump=1)
    assert PAUSE_TAGS.index(second) == PAUSE_TAGS.index(first) + 1


def test_the_notch_stops_at_the_longest_pause():
    assert pause_tag(3.0, boundaries=1, bump=5) == PAUSE_TAGS[-1]


# --- keeping the closest take ----------------------------------------------


def _take(n: int, seconds: float) -> Take:
    return Take(n=n, duration_s=seconds, status="review")


def test_a_take_inside_the_window_wins():
    takes = [_take(1, 8.0), _take(1, 9.5), _take(1, 12.0)]
    assert best_take(takes, (9.0, 10.5)).duration_s == 9.5


def test_the_closest_miss_wins_when_none_land():
    """Three attempts that all missed still produce the best available take.

    Discarding a 10.7s take because it missed by 0.2s, and keeping the 6.0s one
    that happened to come last, would be worse than not correcting at all.
    """
    takes = [_take(1, 6.0), _take(1, 10.7), _take(1, 8.2)]
    assert best_take(takes, (9.0, 10.5)).duration_s == 10.7


def test_best_take_of_nothing_is_nothing():
    assert best_take([], (9.0, 10.5)) is None


