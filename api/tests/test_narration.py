class FakeStore:
    """Enough of S3StorageBackend to prove the take actually gets written."""

    def __init__(self):
        self.objects: dict[str, bytes] = {}

    def put(self, key: str, data: bytes, content_type: str | None = None) -> None:
        self.objects[key] = data

    def get_durable_url(self, key: str) -> str:
        return f"https://example.invalid/{key}"


def test_a_local_file_url_resolves_to_a_path(tmp_path):
    target = tmp_path / "a take.mp3"
    target.write_bytes(b"x")
    assert local_path_of(target.as_uri()) == target


def test_a_url_that_is_not_a_local_file_is_refused():
    with pytest.raises(NarrationError):
        local_path_of("https://example.invalid/take.mp3")


def test_storing_a_take_uploads_the_trimmed_file(padded):
    store = FakeStore()
    take = Take(n=3, local_path=padded, status="ready", duration_s=9.5)
    stored = store_take(take, prefix="cs1-tower-signal", store=store)
    assert stored.uri == "https://example.invalid/cs1-tower-signal/take-03.wav"
    assert store.objects["cs1-tower-signal/take-03.wav"] == padded.read_bytes()


def test_storing_a_take_records_its_digest(padded):
    stored = store_take(
        Take(n=1, local_path=padded, status="ready"), prefix="p", store=FakeStore()
    )
    assert stored.sha256 == sha256_of(padded)


def test_a_failed_take_is_not_uploaded():
    """A block with no audio must not leave a zero-byte object behind."""
    store = FakeStore()
    stored = store_take(Take(n=1, status="failed"), prefix="p", store=store)
    assert stored.uri is None
    assert store.objects == {}


# --- not talking over ourselves --------------------------------------------


def test_narrate_caps_concurrent_calls(tmp_path, specs):
    """Six blocks at once is how the primary provider gets taken away from us.

    Measured on the live CS-1 run of 2026-07-28: six concurrent ElevenLabs
    calls returned `code=rate_limit` and four of six blocks fell through to
    LMNT. A fallback engaged because we flooded the primary ourselves is not
    resilience — it is a self-inflicted narrator change, disclosed in the
    manifest as if the provider had failed.
    """
    inflight, peak = 0, 0

    async def speak(spec, text):
        nonlocal inflight, peak
        inflight += 1
        peak = max(peak, inflight)
        await asyncio.sleep(0)
        try:
            return _render(tmp_path / f"c{peak}-{inflight}-{len(text)}.wav",
                           [("tone", 9.5)]), 0.01
        finally:
            inflight -= 1

    lines = [(n, LINE) for n in range(1, 7)]
    asyncio.run(narrate(lines, specs=specs, window=(9.0, 10.5), speak=speak,
                        concurrency=2, sleep=_no_wait))
    assert peak <= 2


def test_narrate_returns_a_take_per_block(tmp_path, specs):
    lines = [(n, LINE) for n in range(1, 4)]
    takes = asyncio.run(narrate(lines, specs=specs, window=(9.0, 10.5),
                                speak=FakeVoice(tmp_path, [9.5] * 3), sleep=_no_wait))
    assert [t.n for t in takes] == [1, 2, 3]
