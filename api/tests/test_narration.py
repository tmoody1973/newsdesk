# --- fixtures generated by ffmpeg, so the waveform is real ------------------


def _render(path: Path, segments: list[tuple[str, float]]) -> Path:
    """Build a mono wav from ("silence"|"tone", seconds) segments."""
    parts, labels = [], []
    for i, (kind, seconds) in enumerate(segments):
        # `aevalsrc` spells sample rate `s`; `sine` spells it `r`. Not a typo.
        src = "aevalsrc=0:s=44100" if kind == "silence" else "sine=f=440:r=44100"
        parts.append(f"{src}:d={seconds}[s{i}]")
        labels.append(f"[s{i}]")
    graph = ";".join(parts) + f";{''.join(labels)}concat=n={len(segments)}:v=0:a=1[out]"
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-filter_complex", graph,
         "-map", "[out]", str(path)],
        check=True,
    )
    return path


@pytest.fixture
def padded(tmp_path: Path) -> Path:
    """1.0s silence + 3.0s tone + 1.5s silence = 5.5s, 3.0s of which is signal."""
    return _render(tmp_path / "padded.wav",
                   [("silence", 1.0), ("tone", 3.0), ("silence", 1.5)])


@pytest.fixture
def internal_pause(tmp_path: Path) -> Path:
    """Padding at both ends around a line that pauses in the middle."""
    return _render(
        tmp_path / "internal.wav",
        [("silence", 1.0), ("tone", 1.0), ("silence", 0.8),
         ("tone", 1.0), ("silence", 1.0)],
    )


# --- measurement -----------------------------------------------------------


def test_probe_duration_reads_the_real_length(padded):
    assert probe_duration(padded) == pytest.approx(5.5, abs=0.05)


def test_strip_silence_removes_the_lead_and_the_tail(padded, tmp_path):
    out = strip_silence(padded, tmp_path / "trimmed.wav")
    assert probe_duration(out) == pytest.approx(3.0, abs=0.15)


def test_strip_silence_keeps_the_pause_between_sentences(internal_pause, tmp_path):
    """The one thing the trim must not do.

    voice.json measured sentence-end pauses as what fills the ten-second take —
    the only take that landed in window was the choppy one. A trim that ran
    silenceremove with stop_periods=-1 would strip those too and shorten every
    take by exactly the thing that made it work.
    """
    out = strip_silence(internal_pause, tmp_path / "trimmed.wav")
    assert probe_duration(out) == pytest.approx(2.8, abs=0.2)


def test_probe_duration_refuses_a_file_that_is_not_audio(tmp_path):
    bad = tmp_path / "not-audio.wav"
    bad.write_bytes(b"this is not a waveform")
    with pytest.raises(NarrationError):
        probe_duration(bad)


