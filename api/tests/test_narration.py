# --- the chain, walked by us -----------------------------------------------


class FakeVoice:
    """A TTS provider that renders takes of scripted length, at $0.

    Returns real audio, so the take that comes back out is measured by the same
    ffprobe path a live run uses rather than by a number handed to the assertion.
    """

    def __init__(self, tmp_path: Path, script):
        self.tmp_path = tmp_path
        self.script = list(script)
        self.calls: list[tuple[str, str]] = []

    def __call__(self, spec: VoiceSpec, text: str):
        self.calls.append((spec.provider, text))
        outcome = self.script.pop(0) if self.script else 3.0
        if isinstance(outcome, Exception):
            raise outcome
        path = _render(
            self.tmp_path / f"take-{len(self.calls)}.wav",
            [("silence", 0.4), ("tone", outcome), ("silence", 0.6)],
        )
        return path, 0.03


def _run(voice, *, specs, window=(9.0, 10.5), narration=LINE, **kw):
    return asyncio.run(
        run_take(1, narration, specs=specs, window=window, speak=voice,
                 sleep=_no_wait, **kw)
    )


async def _no_wait(_seconds: float) -> None:
    """Backoff is real in production and instant here."""
    return None


@pytest.fixture
def specs():
    return list(voice_specs(KIT_VOICE))


def test_a_take_in_window_is_ready_on_the_primary(tmp_path, specs):
    take = _run(FakeVoice(tmp_path, [9.5]), specs=specs)
    assert take.status == "ready"
    assert take.provider == "elevenlabs"
    assert take.used_fallback is False


def test_the_measured_duration_is_the_trimmed_one(tmp_path, specs):
    """1.0s of padding around a 9.5s take must not be counted as narration."""
    take = _run(FakeVoice(tmp_path, [9.5]), specs=specs)
    assert take.duration_s == pytest.approx(9.5, abs=0.2)
    assert take.raw_duration_s == pytest.approx(10.5, abs=0.2)


def test_a_short_take_is_re_voiced_with_pauses(tmp_path, specs):
    voice = FakeVoice(tmp_path, [7.5, 9.4])
    take = _run(voice, specs=specs)
    assert take.status == "ready"
    assert take.revoices == 1
    assert PAUSE_TAGS[0] in voice.calls[1][1] or PAUSE_TAGS[1] in voice.calls[1][1]


def test_the_first_attempt_is_never_paced(tmp_path, specs):
    """Pacing is a correction, not a default. An unmeasured line gets none."""
    voice = FakeVoice(tmp_path, [9.5])
    _run(voice, specs=specs)
    assert voice.calls[0][1] == LINE


def test_a_long_take_is_flagged_rather_than_re_rolled(tmp_path, specs):
    """An overrun has no lever on this stack, so it costs nothing to find out.

    Re-rolling was tried and measured on the live CS-1 run of 2026-07-28: four
    blocks came back long, each got two fresh renders, and one of the eight
    landed in window. Roughly $0.25 for a one-second change in runtime — which
    is all an overrun costs, since §6.6 derives block length from the take and
    nothing is centred or compressed any more.

    The two prescribed corrections are both unavailable. `voice_settings.speed`
    is not forwarded by the genblaze ElevenLabs adapter, and shortening the line
    would edit words that `claims.py` has already traced to a fact.
    """
    voice = FakeVoice(tmp_path, [11.5, 10.0])
    take = _run(voice, specs=specs)
    assert take.status == "review"
    assert len(voice.calls) == 1


def test_re_voicing_stops_after_two_attempts(tmp_path, specs):
    voice = FakeVoice(tmp_path, [6.0, 6.0, 6.0, 6.0, 6.0])
    take = _run(voice, specs=specs)
    assert len(voice.calls) == MAX_REVOICES + 1
    assert take.status == "review"


def test_a_block_that_never_lands_keeps_its_closest_take(tmp_path, specs):
    take = _run(FakeVoice(tmp_path, [5.0, 8.7, 6.0]), specs=specs)
    assert take.status == "review"
    assert take.duration_s == pytest.approx(8.7, abs=0.2)


def test_a_dead_primary_completes_on_the_fallback(tmp_path, specs):
    """CS-5's TTS leg. A revoked ElevenLabs key must not stop the run."""
    dead = RuntimeError("401 Unauthorized")
    voice = FakeVoice(tmp_path, [dead, dead, dead, dead, 9.6])
    take = _run(voice, specs=specs)
    assert take.status == "ready"
    assert take.provider == "lmnt"
    assert take.used_fallback is True


def test_the_same_model_is_retried_before_the_provider_switch(tmp_path, specs):
    """A transient 401 should not cost a provider substitution.

    Measured on the video leg: the same GMI key succeeded on the next call about
    half the time. Switching narrator voices for that is a visible downgrade
    bought with a retry that would have cleared.
    """
    voice = FakeVoice(tmp_path, [RuntimeError("Backend error (401)"), 9.5])
    take = _run(voice, specs=specs)
    assert take.provider == "elevenlabs"
    assert [p for p, _ in voice.calls] == ["elevenlabs", "elevenlabs"]


def test_a_permanent_failure_does_not_burn_the_backoff(tmp_path, specs):
    """A 404 will not clear. Retrying it three times only delays the fallback."""
    voice = FakeVoice(tmp_path, [RuntimeError("404 voice not found"), 9.5])
    take = _run(voice, specs=specs)
    assert [p for p, _ in voice.calls] == ["elevenlabs", "lmnt"]


def test_a_fully_dead_chain_fails_closed(tmp_path, specs):
    dead = RuntimeError("401 Unauthorized")
    voice = FakeVoice(tmp_path, [dead] * 12)
    take = _run(voice, specs=specs)
    assert take.status == "failed"
    assert take.uri is None
    assert take.local_path is None


def test_every_attempt_is_recorded(tmp_path, specs):
    """The chain is only an honest claim if the record shows what was tried."""
    voice = FakeVoice(tmp_path, [RuntimeError("401"), 9.5])
    take = _run(voice, specs=specs)
    assert len(take.attempts) == 2
    assert take.attempts[0]["provider"] == "elevenlabs"


def test_cost_accumulates_across_every_attempt(tmp_path, specs):
    """A budget that only counts the take that shipped is not a budget."""
    take = _run(FakeVoice(tmp_path, [5.0, 5.0, 9.6]), specs=specs)
    assert take.cost_usd == pytest.approx(0.09, abs=0.001)


def test_the_fallback_is_never_paced(tmp_path, specs):
    """LMNT has neither audio tags nor a rate knob — a tag would be read aloud."""
    dead = RuntimeError("401")
    voice = FakeVoice(tmp_path, [dead, dead, dead, dead, 6.0, 6.0, 6.0])
    _run(voice, specs=specs)
    lmnt_calls = [text for provider, text in voice.calls if provider == "lmnt"]
    assert all(text == LINE for text in lmnt_calls)


